# Export matching static layouts and raster fallbacks for launchers without previewLayout support.
# Previews use neutral placeholders, never real or invented financial amounts.
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$repoRoot = Split-Path $PSScriptRoot -Parent
$resources = Join-Path $repoRoot 'android/app/src/main/res'
$utf8 = [Text.UTF8Encoding]::new($false)
$widgets = @(
    @{ Name = 'today'; Title = '今日支出'; Main = '¥ —'; Detail = '今天的消费'; Width = 160; Height = 180 },
    @{ Name = 'entry'; Title = '账本入口'; Main = '打开账本'; Detail = '查看收支与记录'; Width = 160; Height = 180 },
    @{ Name = 'budget'; Title = '本月预算剩余'; Main = '¥ —'; Detail = '预算进度'; Width = 160; Height = 180 },
    @{ Name = 'month'; Title = '月度收支'; Main = '支出 ¥ —    收入 ¥ —'; Detail = '本月结余 —'; Width = 280; Height = 200 },
    @{ Name = 'upcoming'; Title = '近期扣费 · 未来7天'; Main = '预计扣费'; Detail = '以实际账单为准'; Width = 250; Height = 260 },
    @{ Name = 'recent'; Title = '最近消费'; Main = '消费记录'; Detail = '分类 · 日期 · 金额'; Width = 250; Height = 280 }
)
[IO.Directory]::CreateDirectory((Join-Path $resources 'drawable-nodpi')) | Out-Null
foreach ($widget in $widgets) {
    $mainSize = if ($widget.Name -eq 'month') { 20 } elseif ($widget.Name -eq 'entry') { 24 } else { 28 }
    $bodyMarkup = @"
    <TextView android:layout_width="match_parent" android:layout_height="wrap_content"
      android:text="$($widget.Main)" android:textSize="$($mainSize)sp" android:fontFamily="sans-serif-medium"
      android:textColor="@android:color/black" android:includeFontPadding="false" />
    <TextView android:layout_width="match_parent" android:layout_height="wrap_content" android:layout_marginTop="8dp"
      android:text="$($widget.Detail)" android:textSize="12sp" android:textColor="@android:color/black" />
"@
    if ($widget.Name -in @('recent', 'upcoming')) {
        $rowTitle = if ($widget.Name -eq 'recent') { '消费分类' } else { '预计扣费' }
        $rowCount = if ($widget.Name -eq 'recent') { 3 } else { 2 }
        $bodyMarkup = ''
        for ($row = 0; $row -lt $rowCount; $row++) {
            $bodyMarkup += @"
    <LinearLayout android:layout_width="match_parent" android:layout_height="52dp" android:gravity="center_vertical">
      <LinearLayout android:layout_width="0dp" android:layout_height="wrap_content" android:layout_weight="1" android:orientation="vertical">
        <TextView android:layout_width="match_parent" android:layout_height="wrap_content" android:text="$rowTitle" android:textSize="14sp" android:textColor="@android:color/black" />
        <TextView android:layout_width="match_parent" android:layout_height="wrap_content" android:text="日期" android:textSize="12sp" android:textColor="@android:color/black" />
      </LinearLayout>
      <TextView android:layout_width="wrap_content" android:layout_height="wrap_content" android:text="¥ —" android:textSize="16sp" android:textColor="@android:color/black" />
    </LinearLayout>
"@
        }
    }
    if ($widget.Name -eq 'budget') {
        $bodyMarkup = $bodyMarkup.Replace('    <TextView android:layout_width="match_parent" android:layout_height="wrap_content" android:layout_marginTop="8dp"', @'
    <ProgressBar style="?android:attr/progressBarStyleHorizontal" android:layout_width="match_parent" android:layout_height="6dp"
      android:layout_marginTop="8dp" android:indeterminate="false" android:progress="0" android:progressBackgroundTint="@android:color/darker_gray" />
    <TextView android:layout_width="match_parent" android:layout_height="wrap_content" android:layout_marginTop="8dp"
'@)
    }
    $layout = @"
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/export-widget-previews.ps1. -->
<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android"
  android:layout_width="match_parent" android:layout_height="match_parent" android:padding="16dp"
  android:orientation="vertical" android:background="@drawable/widget_surface">
  <TextView android:layout_width="match_parent" android:layout_height="24dp"
    android:gravity="center_vertical" android:text="$($widget.Title)" android:textSize="13sp"
    android:textColor="@android:color/black" android:includeFontPadding="false" />
  <LinearLayout android:layout_width="match_parent" android:layout_height="0dp" android:layout_weight="1"
    android:orientation="vertical" android:gravity="center_vertical">
$bodyMarkup
  </LinearLayout>
</LinearLayout>
"@
    [IO.File]::WriteAllText((Join-Path $resources "layout/widget_preview_$($widget.Name).xml"), $layout + "`n", $utf8)
    # Render at 3x so launcher scaling keeps text and corners crisp.
    $bitmap = [Drawing.Bitmap]::new($widget.Width * 3, $widget.Height * 3)
    $graphics = [Drawing.Graphics]::FromImage($bitmap)
    $graphics.SmoothingMode = [Drawing.Drawing2D.SmoothingMode]::AntiAlias
    $graphics.TextRenderingHint = [Drawing.Text.TextRenderingHint]::AntiAliasGridFit
    $graphics.Clear([Drawing.Color]::Transparent)
    $graphics.ScaleTransform(3, 3)
    $path = [Drawing.Drawing2D.GraphicsPath]::new()
    $cornerSource = Get-Content (Join-Path $resources 'values/widgets.xml') -Raw
    $radius = [int]([regex]::Match($cornerSource, 'name="widget_corner">(\d+)dp').Groups[1].Value)
    $diameter = $radius * 2
    $path.AddArc(0, 0, $diameter, $diameter, 180, 90)
    $path.AddArc($widget.Width - $diameter, 0, $diameter, $diameter, 270, 90)
    $path.AddArc($widget.Width - $diameter, $widget.Height - $diameter, $diameter, $diameter, 0, 90)
    $path.AddArc(0, $widget.Height - $diameter, $diameter, $diameter, 90, 90)
    $path.CloseFigure()
    $graphics.FillPath([Drawing.Brushes]::White, $path)
    function Draw-Label([string]$label, [single]$size, [single]$x, [single]$y, [bool]$bold = $false) {
        $style = if ($bold) { [Drawing.FontStyle]::Bold } else { [Drawing.FontStyle]::Regular }
        $font = [Drawing.Font]::new('Microsoft YaHei UI', $size, $style, [Drawing.GraphicsUnit]::Pixel)
        $graphics.DrawString($label, $font, [Drawing.Brushes]::Black, $x, $y)
        $font.Dispose()
    }
    Draw-Label $widget.Title 13 16 20
    $bodyY = 40 + ($widget.Height - 56 - 56) / 2
    if ($widget.Name -in @('recent', 'upcoming')) {
        $rowsY = 40 + ($widget.Height - 56 - 52 * $rowCount) / 2
        for ($row = 0; $row -lt $rowCount; $row++) {
            Draw-Label $rowTitle 14 16 ($rowsY + $row * 52)
            Draw-Label '日期' 12 16 ($rowsY + $row * 52 + 22)
            Draw-Label '¥ —' 16 ($widget.Width - 64) ($rowsY + $row * 52 + 9) $true
        }
    } else {
        Draw-Label $widget.Main $mainSize 16 $bodyY $true
        if ($widget.Name -eq 'budget') {
            $pen = [Drawing.Pen]::new([Drawing.Color]::Gray, 4)
            $graphics.DrawLine($pen, 16, $bodyY + 40, $widget.Width - 16, $bodyY + 40)
            $pen.Dispose()
            Draw-Label $widget.Detail 12 16 ($bodyY + 49)
        } else {
            Draw-Label $widget.Detail 12 16 ($bodyY + 40)
        }
    }
    $bitmap.Save((Join-Path $resources "drawable-nodpi/widget_preview_$($widget.Name).png"), [Drawing.Imaging.ImageFormat]::Png)
    $path.Dispose()
    $graphics.Dispose()
    $bitmap.Dispose()
}
